import { chromium } from 'playwright';
import { makeL } from './i18n.mjs';
const out = process.argv[2];
const lang = process.argv[3] || 'zh';
const L = makeL(lang);
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1, colorScheme: 'dark' });
const page = await ctx.newPage();
await page.addInitScript((l) => localStorage.setItem('language', l), lang);
await page.addLocatorHandler(page.getByRole('button', { name: L('Maybe Later'), exact: true }), async (b) => b.click());
let n = 0;
const shot = async (name) => page.screenshot({ path: `${out}/x${String(++n).padStart(2, '0')}-${name}.png` });
await page.goto('http://127.0.0.1:5199/');
await page.waitForTimeout(1200);
await page.getByRole('button', { name: L('Maybe Later'), exact: true }).click().catch(() => {});
await page.waitForTimeout(400);
await shot('home');
await page.getByRole('button', { name: L('Create chain', 'dashboard.dashboardEmptyState.createChain'), exact: true }).first().click();
await page.waitForTimeout(600);
await shot('editor');
await page.getByLabel(L('Chain name'), { exact: true }).fill('论文写作');
await page.locator('#sacred-seat-trigger').selectOption({ index: 1 });
await page.locator('#auxiliary-signal').selectOption({ index: 1 });
await page.locator('#task-description').fill('以最好的状态专注写作');
await shot('editor-filled');
await page.mouse.wheel(0, 900);
await page.waitForTimeout(300);
await shot('editor-filled-2');
await page.getByRole('button', { name: L('Create chain'), exact: true }).last().click();
await page.waitForTimeout(800);
await shot('home-chain');
const buttons = await page.getByRole('button').allInnerTexts();
console.log('buttons:', JSON.stringify(buttons));
await page.getByRole('button', { name: L('Schedule'), exact: true }).first().click();
await page.waitForTimeout(800);
await shot('scheduled');
await page.getByRole('button', { name: L('Start'), exact: true }).first().click();
await page.waitForTimeout(1500);
await shot('focus');
console.log('focus buttons:', JSON.stringify(await page.getByRole('button').allInnerTexts()));
await page.getByRole('button', { name: L('Pause'), exact: true }).click();
await page.waitForTimeout(800);
await shot('pause-dialog');
await page.keyboard.press('Escape');
await page.waitForTimeout(500);
await shot('after-escape');
await browser.close();
